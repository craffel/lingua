def copy_dir(input_dir: str, output_dir: str) -> None:
    print(f"Copying : {input_dir}\n" f"to      : {output_dir} ...")
    assert os.path.isdir(input_dir), f"{input_dir} is not a directory"
    assert os.path.isdir(output_dir), f"{output_dir} is not a directory"
    rsync_cmd = (
        f"rsync -arm --copy-links "
        f"--include '**/' "
        f"--include '*.py' "
        f"--exclude='*' "
        f"{input_dir}/ {output_dir}"
    )
    print(f"Copying command: {rsync_cmd}")
    subprocess.call([rsync_cmd], shell=True)
    print("Copy done.")


def validate_args(args) -> None:
    if hasattr(args, "anaconda") and args.anaconda:
        if args.anaconda == "default":
            args.anaconda = (
                subprocess.check_output("which python", shell=True)
                .decode("ascii")
                .strip()
            )
        else:
            args.anaconda = f"{args.anaconda}/bin/python"
        assert os.path.isfile(args.anaconda), f"Python not found at {args.anaconda}"

    args.mem = args.mem or "0"

    assert args.ngpu > 0, "Number of GPUs must be positive"
    assert args.ncpu > 0, "Number of CPUs must be positive"
    assert args.nodes > 0, "Number of nodes must be positive"
    assert os.path.isdir(args.rocm_home), f"ROCm not found at {args.rocm_home}"


def launch_job(args: AMDToolArgs):
    # Set up args default and validate them
    validate_args(args)
    dump_dir = args.config["dump_dir"]
    job_name = args.config["name"]

    from pathlib import Path
    if not Path(dump_dir).parent.exists():
        dump_dir = dump_dir.replace("/fsx/craffel/lingua_logs", "/u/gsaltintas/lingua_logs/")
        args.config["dump_dir"] = dump_dir

    # Prepare data copy commands
    copy_data_command = ""
    if False: #"data" in args.config:
        data_dir = args.data_dir
        data_root_dir = args.config["data"]["root_dir"]
        data_sources = args.config["data"]["sources"]
        
        for source in data_sources.keys():
            copy_data_command += f"echo 'Copying data for {source}...'\n"
            copy_data_command += f"mkdir -p {data_root_dir}/{source}\n"
            if os.path.exists(f"{data_dir}/{source}"):
                copy_data_command += f"rsync -arm -v --stats --progress {data_dir}/{source}/ {data_root_dir}/{source}/\n"
            else:
                copy_data_command += f"echo 'Warning: Source {data_dir}/{source} not found, skipping...'\n"

    print("Creating directories...")
    os.makedirs(dump_dir, exist_ok=args.dirs_exists_ok or args.override)
    if args.override:
        confirm = input(
            f"Are you sure you want to delete the directory '{dump_dir}'? This action cannot be undone. (yes/no): "
        )
        if confirm.lower() == "yes":
            shutil.rmtree(dump_dir)
            os.makedirs(dump_dir)
            print(f"Directory '{dump_dir}' has been deleted and recreated.")
        else:
            print("Operation cancelled.")
            return
    
    os.makedirs(os.path.join(dump_dir, "logs"), exist_ok=args.dirs_exists_ok)
    os.makedirs(os.path.join(dump_dir, "wandb"), exist_ok=args.dirs_exists_ok)
    
    if args.copy_code:
        os.makedirs(f"{dump_dir}/code", exist_ok=args.dirs_exists_ok)
        print("Copying code ...")
        copy_dir(os.getcwd(), f"{dump_dir}/code")

    print("Saving config file ...")
    with open(f"{dump_dir}/base_config.yaml", "w") as cfg:
        cfg.write(OmegaConf.to_yaml(args.config))

    # Setup environment paths
    conda_env_path = os.path.dirname(os.path.dirname(args.anaconda))
    project_folder = f"{dump_dir}/code" if args.copy_code else os.getcwd()
    
    # GPU IDs (e.g., "0" for single GPU, "0,1,2,3" for 4 GPUs)
    gpu_ids = ",".join(str(i) for i in range(args.ngpu))
    
    # Rendezvous ID (use a random number for multi-run isolation)
    import random
    rdzv_id = random.randint(100000, 999999)
    
    # Log redirection
    if args.stdout:
        log_redirect = ""
        log_suffix = ""
    else:
        timestamp = "$(date +%Y%m%d_%H%M%S)"
        log_redirect = ""
        log_suffix = f" > {dump_dir}/logs/train_{timestamp}.log 2>&1"
    
    # Generate launch script for single node (node_rank=0)
    launch_script = TORCHRUN_SCRIPT.format(
        dump_dir=dump_dir,
        project_folder=project_folder,
        conda_env_path=conda_env_path,
        rocm_home=args.rocm_home,
        gpu_ids=gpu_ids,
        master_addr=args.master_addr,
        master_port=args.master_port,
        rdzv_id=rdzv_id,
        ngpu=args.ngpu,
        nodes=args.nodes,
        node_rank=0,  # For single node, always 0
        script=args.script,
        copy_data_command=copy_data_command,
        log_redirect=log_redirect,
        log_suffix=log_suffix,
    )

    print("Writing launch script ...")
    script_path = f"{dump_dir}/launch.sh"
    with open(script_path, "w") as f:
        f.write(launch_script)
    
    # Make script executable
    os.chmod(script_path, 0o755)

    if args.nodes > 1:
        print("\n" + "="*60)
        print("MULTI-NODE SETUP INSTRUCTIONS")
        print("="*60)
        print(f"\nYou specified {args.nodes} nodes. To run multi-node training:")
        print(f"\n1. On the MASTER node (rank 0):")
        print(f"   bash {script_path}")
        print(f"\n2. On each WORKER node (rank 1, 2, ...):")
        print(f"   Edit {script_path} and change:")
        print(f"   --node-rank=0  -->  --node-rank=<worker_rank>")
        print(f"   --master-addr={args.master_addr}  -->  --master-addr=<master_ip>")
        print(f"\n3. Ensure all nodes can communicate on port {args.master_port}")
        print(f"\n4. Update NCCL_SOCKET_IFNAME to your network interface (e.g., ib0, eth0)")
        print("="*60 + "\n")
    else:
        print(f"\nLaunching single-node training on {args.ngpu} GPU(s)...")
        if args.launcher == "bash":
            os.system(f"bash {script_path}")
        else:
            print(f"Script ready at: {script_path}")
            print(f"Run with: bash {script_path}")

    print("Done.")


if __name__ == "__main__":
    """
    The command line interface here uses OmegaConf https://omegaconf.readthedocs.io/en/2.3_branch/usage.html#from-command-line-arguments
    This accepts arguments as a dot list
    
    Example usage:
        python amdtool.py config=configs/my_config.yaml ngpu=4 nodes=1
        python amdtool.py config=configs/my_config.yaml ngpu=8 nodes=2 master_addr=192.168.1.100
    """
    args = OmegaConf.from_cli()
    if isinstance(args.config, MutableSequence):
        args.config = OmegaConf.merge(*[OmegaConf.load(c) for c in args.config])
    else:
        args.config = OmegaConf.load(args.config)
    args = dataclass_from_dict(AMDToolArgs, args)
    launch_job(args)
